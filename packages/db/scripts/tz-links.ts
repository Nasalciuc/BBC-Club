/**
 * Writes `packages/db/src/tz-links.ts`: tzdata's links (`L <target> <alias>` in tzdata.zi), each alias to the zone it
 * names, so a name a Postgres without Debian's tzdata-legacy cannot read (`Asia/Calcutta`) is read as its zone
 * (`Asia/Kolkata`) — ADR-IMPL-077 §5, #114.
 *
 *   bun run --filter @bbc/db tz:links -- path/to/tzdata.zi          # the new Postgres image's (RUNBOOK)
 *   bun run --filter @bbc/db tz:links -- path/to/tzdata.zi --check  # fails when the committed file differs
 *   bun run --filter @bbc/db tz:links                               # this machine's /usr/share/zoneinfo/tzdata.zi
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "../src/tz-links.ts");
const args = process.argv.slice(2);
const check = args.includes("--check");
const source = args.find((a) => !a.startsWith("--")) ?? "/usr/share/zoneinfo/tzdata.zi";

export function linksOf(zi: string): { version: string; links: Map<string, string> } {
  const version = /^# version (\S+)/m.exec(zi)?.[1];
  if (!version) throw new Error("tzdata.zi without a `# version` line");
  const direct = new Map<string, string>();
  for (const line of zi.split("\n")) {
    const [kind, target, alias] = line.trim().split(/\s+/);
    if (kind === "L" && target && alias) direct.set(alias, target);
  }
  // A link to a link names the zone at the end of the chain (none in 2026c; tzdata allows them).
  const links = new Map<string, string>();
  for (const alias of [...direct.keys()].sort()) {
    let target = direct.get(alias) ?? alias;
    for (let hops = 0; direct.has(target) && hops < 10; hops++) target = direct.get(target) ?? target;
    links.set(alias, target);
  }
  return { version, links };
}

export function render(version: string, links: Map<string, string>): string {
  // Keys as Prettier writes them: bare where a name is an identifier (`Cuba`, `GMT0`), quoted otherwise.
  const key = (alias: string) => (/^[A-Za-z_$][\w$]*$/.test(alias) ? alias : JSON.stringify(alias));
  const rows = [...links].map(([alias, target]) => `  ${key(alias)}: ${JSON.stringify(target)},`);
  return `/**
 * Generated by packages/db/scripts/tz-links.ts from tzdata ${version}'s tzdata.zi (its \`L <target> <alias>\` lines);
 * do not edit — run \`bun run --filter @bbc/db tz:links\` again after a tzdata release. Each alias to the zone it
 * names (ADR-IMPL-077 §5).
 */
export const TZ_LINKS_TZDATA = ${JSON.stringify(version)};

export const TZ_LINKS: Readonly<Record<string, string>> = {
${rows.join("\n")}
};
`;
}

if (import.meta.main) {
  const { version, links } = linksOf(readFileSync(source, "utf8"));
  const text = render(version, links);
  if (check) {
    const committed = readFileSync(OUT, "utf8");
    if (committed !== text) {
      console.error(`tz-links.ts differs from ${source} (tzdata ${version}): run bun run --filter @bbc/db tz:links`);
      process.exit(1);
    }
    console.log(`tz-links.ts matches ${source} (tzdata ${version}, ${links.size} links)`);
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote tz-links.ts: tzdata ${version}, ${links.size} links`);
  }
}
